/**
 * 富文本编辑区**回写**时的 Markdown 清理。
 *
 * 编辑区显示的是渲染后的稿子，失焦时用 turndown 把 DOM 转回 Markdown。
 * turndown 会做一些"防御性转义"——行首的 `1. ` 会被写成 `1\. `，
 * 免得 Markdown 把它当成有序列表。可**模块标题恰好就是这种形式**
 * （`# 1. Let's say!`），转义后标题不再等于模块标题：
 *
 * 1. 回写结果与生成结果逐字不同 → 光点一下正文就变成"未保存修改"；
 * 2. 下一次规范化认不出这个标题 → **再插一行模块标题**，
 *    实测表现是每点一次模块，正文开头就多一行 `Let's say!`。
 *
 * 所以这里把转义还原。规则很窄：只认行首「数字 + 反斜杠点」，
 * 不做通用反转义——正文里的 `\_`、`\*` 是 turndown 对**字面字符**的保护，动它们会改坏内容。
 */
export function normalizeRoundTripMarkdown(markdown: string): string {
  return (
    markdown
      // 转义出现在**文本开头**，标题的话就在 `# ` 之后（`# 1\. Let's say!`），
      // 所以前缀要一起吃掉、再原样放回。
      .replace(/^(#{1,6}\s+)?(\d+)\\\./gmu, "$1$2.")
      // 不间断空格与行尾空白是 DOM 转换的排版痕迹，不是正文。
      .replace(/ /gu, " ")
      .replace(/[ \t]+$/gmu, "")
      .replace(/\n{3,}/g, "\n\n")
      .trim()
  );
}
